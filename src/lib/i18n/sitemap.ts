/**
 * `sitemap.xml` 的**唯一生成处**。
 *
 * 21 条 URL，每条带 4 条 `xhtml:link`（三语言 + `x-default`）。互指集合与页面
 * `<head>` 里的 `hreflang` 取自同一个 `listHreflang`，因此两处不可能不一致。
 *
 * 与 `entry-html.ts` 一样不得 import React 或浏览器全局：`vite.config.ts` 在
 * 构建期调用它。
 */
import { listHreflang } from "./hreflang";
import { LOCALES, type LocaleCode } from "./locales";
import { DEFAULT_HOME_PATH, toolPathInLocale } from "./routes";
import { ALL_TOOL_ROUTES } from "./seo-content";
import type { ToolRoute } from "./tool-routes";

/** 站点 URL 占位符，由 siteMetaPlugin 在构建期替换为真实主机。 */
const SITE_URL_TOKEN = "__SITE_URL__";

/** 各工具页的抓取优先级；首页最高。 */
const PRIORITY: Record<ToolRoute, string> = {
  home: "1.0",
  "video-frame": "0.9",
  "video-compress": "0.9",
  "image-compress": "0.9",
  "image-watermark": "0.9",
  "id-photo": "0.9",
  "image-a4-layout": "0.9",
};

/** `lastmod` 需要稳定：用构建日期会让每次构建都产生 diff。 */
export const SITEMAP_LASTMOD = "2026-10-12";

const escapeXml = (value: string): string =>
  value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

/**
 * 生成完整 sitemap。`__SITE_URL__` 保留为占位符，交由既有的 siteMetaPlugin
 * 注入，使换域名只需改一处。
 */
export const renderSitemap = (): string => {
  const urls = (Object.keys(LOCALES) as LocaleCode[]).flatMap((locale) =>
    ALL_TOOL_ROUTES.map((route) => {
      const path = toolPathInLocale(locale, route);
      const alternates = listHreflang(locale, route)
        .map(
          (entry) =>
            `    <xhtml:link rel="alternate" hreflang="${entry.hreflang}" href="${escapeXml(
              `${SITE_URL_TOKEN}${entry.path}`,
            )}" />`,
        )
        .join("\n");
      return `  <url>
    <loc>${escapeXml(`${SITE_URL_TOKEN}${path}`)}</loc>
    <lastmod>${SITEMAP_LASTMOD}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>${PRIORITY[route]}</priority>
${alternates}
  </url>`;
    }),
  );

  // 生成标记：插件据此区分「本次新建」与「覆盖既有文件」，清理时分别删除或恢复
  return `<!-- generated by offline-tools:i18n-entries -->
<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${urls.join("\n")}
</urlset>
`;
};

/** sitemap 中应有的全部 URL 路径（21 条），供测试断言使用。 */
export const sitemapPaths = (): readonly string[] =>
  (Object.keys(LOCALES) as LocaleCode[]).flatMap((locale) =>
    ALL_TOOL_ROUTES.map((route) => toolPathInLocale(locale, route)),
  );

export { DEFAULT_HOME_PATH };
