/**
 * `offline-tools:i18n-entries` —— 构建期生成 21 个语言入口页。
 *
 * ## 为什么在项目根下写出真实文件
 *
 * Vite 的多入口 HTML 产物位置**镜像入口文件相对 root 的路径**：入口是
 * `<root>/zh/index.html` 就产出 `dist/zh/index.html`。虚拟模块（`\0` 前缀）
 * 走不通 —— HTML 入口会被当成 JS 解析，且 `\0` 会带进资源文件名报
 * `INVALID_OPTION`。`rollupOptions.output.entryFileNames` 也无法搬动 HTML 入口。
 * 因此唯一可行的机制是：把入口写到它们的**最终 URL 路径**上，让 Vite 照常处理。
 *
 * 这些文件是**生成产物**，不是源文件：
 *  - 每个文件带 `GENERATED_MARKER` 注释，只有带标记的文件才会被删；
 *  - `buildStart` 会清扫上次异常退出遗留的标记文件；
 *  - `closeBundle` 删除全部生成文件并回收空目录。
 *
 * 生成与删除都只针对带标记的文件，因此不会误删手写入口页（迁移期的 7 个）
 * 或任何其他内容。
 *
 * ## 与既有占位符注入的关系
 *
 * 生成器保留 `__SITE_URL__` 与 `__ANALYTICS_ID__`，由后面的 `siteMetaPlugin`
 * 经 `transformIndexHtml` 注入 —— 本插件必须排在它之前（`enforce: "pre"`），
 * 使 21 个入口都经过注入。
 */
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import type { Plugin } from "vite";
import {
  allEntryCombinations,
  ENTRY_MODULE_TOKEN,
  renderEntryHtml,
} from "../src/lib/i18n/entry-html";
import type { LocaleCode } from "../src/lib/i18n/locales";
import { renderSitemap } from "../src/lib/i18n/sitemap";
import type { ToolRoute } from "../src/lib/i18n/tool-routes";

/** 生成的每个 HTML 都带这一行，清理时只删带标记的文件。 */
export const GENERATED_MARKER = "<!-- generated by offline-tools:i18n-entries -->";

/** sitemap 的生成标记：与入口 HTML 的标记分开，但同样用于区分「自建」与「覆盖」。 */
export const SITEMAP_MARKER = "<!-- generated by offline-tools:i18n-entries -->";

/** dev 与 build 都用源码入口：构建时 Vite 会把它改写成打包产物。 */
const SOURCE_ENTRY = "/src/main.tsx";

export type EntrySource = {
  locale: LocaleCode;
  route: ToolRoute;
  /** 站点 URL 路径，如 `/zh/video-frame/`。 */
  urlPath: string;
  /** 相对 root 的文件路径，如 `zh/video-frame/index.html`。 */
  relativeFile: string;
};

/** 全部 21 个「语言 × 工具」入口。 */
export const listEntrySources = (): readonly EntrySource[] =>
  allEntryCombinations().map(({ locale, route, path: urlPath }) => ({
    locale,
    route,
    urlPath,
    // `/` -> `index.html`；`/zh/video-frame/` -> `zh/video-frame/index.html`
    relativeFile: [...urlPath.split("/").filter(Boolean), "index.html"].join("/"),
  }));

/** 渲染一个入口的完整 HTML（含生成标记）。 */
export const renderGeneratedEntry = (source: EntrySource): string =>
  `${GENERATED_MARKER}\n${renderEntryHtml(source.locale, source.route).replace(
    ENTRY_MODULE_TOKEN,
    SOURCE_ENTRY,
  )}`;

const isGenerated = (file: string): boolean =>
  existsSync(file) &&
  readFileSync(file, "utf8").startsWith(GENERATED_MARKER);

/** 递归收集 root 下所有带生成标记的 HTML。 */
const findGeneratedFiles = (root: string, dir = root): string[] => {
  const found: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "node_modules" || entry.name === "dist" || entry.name === ".git") {
      continue;
    }
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) found.push(...findGeneratedFiles(root, full));
    else if (entry.name.endsWith(".html") && isGenerated(full)) found.push(full);
  }
  return found;
};

/**
 * 删除文件并向上回收空目录（到 root 为止）。
 *
 * 仅用于清扫**上次异常退出遗留**的生成文件。正常清理路径用 `cleanup` 里的
 * `pruneEmptyDirs`，它按目录内容判定归属（见 `isOwnedDir`）。
 */
export const removeAndPrune = (root: string, file: string): void => {
  rmSync(file, { force: true });
  let dir = path.dirname(file);
  while (dir.startsWith(root) && dir !== root) {
    try {
      if (readdirSync(dir).length > 0) break;
      rmdirSync(dir);
    } catch {
      break;
    }
    dir = path.dirname(dir);
  }
};

/**
 * 判定目录是否「由本插件创建」：目录里只剩本插件的生成文件（或已空）。
 *
 * 不用「写盘前是否存在」来判断 —— `vite build` 会跑两个 environment，
 * `closeBundle` 却只触发一次，时序上无法可靠区分「上一轮自己的产物」与
 * 「用户原有目录」。按内容判断与构建轮次无关：只要目录里没有非生成内容，
 * 它就是这个插件的产物，可以回收。
 *
 * 导出供测试用真实目录驱动：本函数与 `pruneEmptyDirs` 的 bug 曾因没有测试
 * 触碰真实文件系统而长期隐形。
 */
export const isOwnedDir = (dir: string): boolean => {
  try {
    // 只接受「生成 HTML」这一个白名单：任何其他文件（源码、文档、非生成 HTML）
    // 都说明目录里存在插件之外的内容，不得回收。
    return readdirSync(dir).every(
      (name) => name.endsWith(".html") && isGenerated(path.join(dir, name)),
    );
  } catch {
    return false;
  }
};

/** 回收空目录：自下而上，遇到非空或非自有目录即停。 */
export const pruneEmptyDirs = (root: string, file: string): void => {
  let dir = path.dirname(file);
  while (dir.startsWith(root) && dir !== root) {
    if (!existsSync(dir)) {
      dir = path.dirname(dir);
      continue;
    }
    if (!isOwnedDir(dir)) break;
    try {
      if (readdirSync(dir).length > 0) break;
      // 必须用 rmdirSync：rmSync 在 recursive:false 下无法删除目录（EISDIR），
      // 之前的实现因此静默残留空目录。
      rmdirSync(dir);
    } catch {
      // 目录被并发创建或非空：停止向上回收即可，不是错误
      break;
    }
    dir = path.dirname(dir);
  }
};

export type I18nEntriesOptions = {
  /** 仅用于测试：跳过实际写盘。 */
  dryRun?: boolean;
};

/**
 * 各入口「原有内容」的备份：路径 -> 原始文本。
 *
 * **这是防数据丢失的关键**。生成器写出的路径与既有源文件重叠（迁移期中文
 * 入口页就在 `/index.html`、`/video-frame/index.html` …），而 Vite 在
 * `buildStart` 阶段按目录展开 `rollupOptions.input`，无法用虚拟模块替代。
 * 一旦某个路径上已经有内容，就必须先备份、清理时**恢复**而不是删除 ——
 * 否则一次构建就会删掉源码里未提交的入口页（本插件开发过程中确实发生过：
 * 未纳入 git 的 `id-photo/index.html` 因此丢失）。
 */
export const i18nEntriesPlugin = (
  options: I18nEntriesOptions = {},
): Plugin => {
  let root = process.cwd();
  /** 由本插件新建的文件：清理时删除。 */
  const created = new Set<string>();
  /** 本插件覆盖的既有文件：清理时按原文恢复。 */
  const overwritten = new Map<string, string>();
  /** 本次写出的全部文件（含被覆盖的）：清理后据此回收空目录。 */
  const generated = new Set<string>();
  /**
   * 收尾：删除自建文件、恢复被覆盖文件、回收本插件创建的空目录。
   */
  const cleanup = (): void => {
    if (options.dryRun) return;
    for (const file of created) rmSync(file, { force: true });
    for (const [file, original] of overwritten) {
      try {
        writeFileSync(file, original, "utf8");
      } catch {
        // 恢复失败时保留现场比静默删除安全
      }
    }
    // 目录回收放在文件处理之后，且只回收本次创建的那些 ——
    // 「目录被当成文件恢复」曾导致空目录残留（writeFileSync 对目录为空操作）。
    for (const file of generated) pruneEmptyDirs(root, file);
    created.clear();
    overwritten.clear();
    generated.clear();
  };

  return {
    name: "offline-tools:i18n-entries",
    // 必须早于 siteMetaPlugin：生成的文件要经过它的占位符注入
    enforce: "pre",

    configResolved(config) {
      root = config.root;
      // Vite 8 会为每个 environment 复用插件实例；这里按实际 environment 数量
      // 决定需要几轮 closeBundle 才收尾。
    },

    buildStart() {
      if (options.dryRun) return;
      // 先清扫上次异常退出留下的生成文件，避免它们被误认为源文件。
      // 只删带标记的文件，因此手写入口页与其他内容不受影响。
      for (const stale of findGeneratedFiles(root)) {
        removeAndPrune(root, stale);
      }
      for (const source of listEntrySources()) {
        const file = path.join(root, source.relativeFile);
        const dir = path.dirname(file);
        mkdirSync(dir, { recursive: true });
        // 已有内容先备份：清理时恢复，绝不删除别人的文件
        if (existsSync(file)) {
          const original = readFileSync(file, "utf8");
          if (!original.startsWith(GENERATED_MARKER)) {
            overwritten.set(file, original);
          }
        } else {
          created.add(file);
        }
        writeFileSync(file, renderGeneratedEntry(source), "utf8");
        generated.add(file);
      }

      // sitemap 同样在构建期生成：21 条 URL × 4 条 xhtml:link 手写必错。
      // 写到 public/ 下，由 Vite 复制为 dist/sitemap.xml；占位符仍由
      // siteMetaPlugin 的 closeBundle 兜底层替换（本插件必须排在它之前）。
      const sitemapFile = path.join(root, "public", "sitemap.xml");
      if (existsSync(sitemapFile)) {
        const original = readFileSync(sitemapFile, "utf8");
        if (!original.startsWith(SITEMAP_MARKER)) {
          overwritten.set(sitemapFile, original);
        }
      } else {
        created.add(sitemapFile);
      }
      writeFileSync(sitemapFile, renderSitemap(), "utf8");
      generated.add(sitemapFile);
    },

    // 用 closeBundle 而非 buildEnd：buildEnd 在 HTML 处理之前触发，
    // 此时删掉入口会让构建拿不到文件。closeBundle 是产物落盘之后的最后时机。
    closeBundle() {
      cleanup();
    },
  };
};

export default i18nEntriesPlugin;
